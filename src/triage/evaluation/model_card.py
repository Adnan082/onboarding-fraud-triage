"""The model card, generated from the manifest and ``reports/metrics.json``.

A model card answers "what is this, what is it for, and where does it fail?" for
someone who did not build it. It overlaps the validation report deliberately: the
report is for a reviewer assessing the model, the card travels with the model
itself.

Generated for the same reason as everything else (rule 6). A card that says a
model excludes age while the manifest says otherwise is worse than no card, and
generating it makes that contradiction impossible.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from triage.evaluation.artefacts import format_interval, format_number

MISSING = "_Not generated: run `make train` first._"


def _pct(value: float | None, digits: int = 1) -> str:
    return "n/a" if value is None else f"{value * 100:.{digits}f}%"


def render(metrics: dict[str, Any], manifest: dict[str, Any] | None) -> str:
    """The card, as markdown."""
    if not manifest:
        return f"# Model card\n\n{MISSING}\n"

    champion = metrics.get("champion", {})
    policy = metrics.get("policy", {})
    monitoring = metrics.get("monitoring", {})
    service = metrics.get("service", {})

    lines = [
        "# Model card — onboarding fraud triage champion",
        "",
        f"**Version:** `{manifest['model_version']}`  ",
        f"**Trained:** {str(manifest.get('created_at', ''))[:10]} on "
        f"{manifest['model']['n_train']:,} applications "
        f"({manifest['model']['n_train_fraud']:,} frauds)  ",
        f"**Config hash:** `{manifest.get('config_hash', '?')}` · "
        f"**Commit:** `{manifest.get('git_sha', '?')}`  ",
        f"**Calibration:** {manifest['calibration']['method']}",
        "",
        "> Generated by `make report` from `models/manifest.json` and",
        "> `reports/metrics.json`. Not typed by hand.",
        "",
        "## What it does",
        "",
        "Scores an online bank-account application for fraud and routes it to one of three",
        "outcomes: **approve**, **send to a human reviewer**, or **ask for extra",
        "verification**. The score is turned into a decision by a label-conditional",
        "conformal policy, so the band carries a stated guarantee rather than a bare",
        "threshold.",
        "",
        "**It never declines an application.** The strongest action available to it is to",
        "ask for more checks.",
        "",
        "## Intended use, and what it is not for",
        "",
        "- **Intended:** triaging incoming applications inside a fraud operations team, as",
        "  one input among several, with a human on every non-approval.",
        "- **Not intended:** automatic refusal, any decision about an existing customer,",
        "  any use on real customer data. This is a portfolio project trained on public",
        "  synthetic data.",
        "- **Reason codes are for analysts.** They explain a model output to someone",
        "  trained to read it. They are not an explanation owed to an applicant, and no",
        "  interface shows them to one.",
        "",
        "## Inputs",
        "",
        f"{len(manifest['features'])} features, validated against a frozen data contract",
        "before scoring. An application that breaches the contract is rejected rather than",
        "scored.",
        "",
        f"**`customer_age` is not among them** "
        f"({'confirmed' if 'customer_age' not in manifest['features'] else 'WARNING: present'}).",
        "It is accepted by the API and logged so fairness can be measured, then dropped",
        "before the model sees anything. Age is used to measure this system and, in two",
        "experiments, as a training-time constraint. It never decides anything.",
        "",
        "## Performance",
        "",
    ]

    if champion:
        lines += [
            "| Month | ROC-AUC | Fraud caught | False alarms | Brier |",
            "|---|---|---|---|---|",
        ]
        for month, values in sorted(champion.get("months", {}).items()):
            lines.append(
                f"| {month} | {format_number(values['discrimination']['roc_auc'])} "
                f"| {_pct(values['realised']['tpr'])} "
                f"| {_pct(values['realised']['fpr'])} "
                f"| {format_number(values['calibration']['overall']['brier'], 4)} |"
            )
        lines += [
            "",
            "Evaluated on two months the model never saw, reported separately. Trained on",
            "months 0-4, calibrated on month 5.",
        ]
    else:
        lines.append(MISSING)

    lines += ["", "## Fairness", ""]
    if champion:
        lines += ["| Month | Under 50 | 50 and over | Ratio (95% CI) |", "|---|---|---|---|"]
        for month, values in sorted(champion.get("months", {}).items()):
            groups = {r["group"]: r for r in values["fairness"]["by_group"]}
            lines.append(
                f"| {month} | {_pct(groups.get('age<50', {}).get('fpr'))} "
                f"| {_pct(groups.get('age>=50', {}).get('fpr'))} "
                f"| {format_interval(values['fairness'].get('fpr_ratio_ci'))} |"
            )
        lines += [
            "",
            "False-alarm rates among genuine applicants, by age group. **Older applicants",
            "are stopped materially more often than younger ones**, and dropping the age",
            "column did not fix that: other fields carry the same information. The",
            "mitigation experiments in the validation report quantify what each attempted",
            "fix cost.",
        ]

    if policy:
        chosen = policy.get("chosen", {})
        lines += [
            "",
            "## The decision policy",
            "",
            f"`alpha_fraud = {chosen.get('alpha_fraud')}`, "
            f"`alpha_legit = {chosen.get('alpha_legit')}`, giving a promise of catching at",
            f"least **{_pct(1 - float(chosen.get('alpha_fraud', 0)), 0)}** of fraud while",
            f"sending at most **{_pct(float(chosen.get('alpha_legit', 0)), 0)}** of genuine",
            "applicants for extra verification.",
            "",
            "**That second promise did not hold on the test months.** The guarantee is",
            "conditional on new applications being exchangeable with the calibration month,",
            "and they were not. This is the single most important caveat on the model, and",
            "it is why the monitor exists.",
            "",
            "The alpha values and the review capacity behind them are **owner assumptions**,",
            "not properties of the data.",
        ]

    if monitoring:
        calibration = monitoring.get("threshold_calibration", {})
        lines += [
            "",
            "## Monitoring",
            "",
            "Three label-free detectors run per 4,000-application window, with thresholds",
            f"calibrated on {calibration.get('clean_windows', '?')} clean windows. On alert,",
            "the policy tightens its alphas so more applications reach a human, and the",
            "event is logged. The fallback is never cleared automatically.",
        ]

    if service:
        latency = service.get("latency", {})
        without = latency.get("http_without_shap", {})
        with_shap = latency.get("http_with_shap", {})
        lines += [
            "",
            "## Serving",
            "",
            f"p50 **{format_number(without.get('p50_ms'), 3)} ms** without reason codes,",
            f"**{format_number(with_shap.get('p50_ms'), 4)} ms** with them, on CPU. Reason",
            "codes cost roughly twenty times the latency budget, so a caller that does not",
            "need them should ask for `?explain=false`.",
            "",
            "The service verifies every artefact hash against the manifest at startup and",
            "refuses to serve on a mismatch.",
        ]

    lines += [
        "",
        "## Caveats and limitations",
        "",
        "- **Synthetic data.** Generated from an anonymised real dataset; not UK data. No",
        "  rate here transfers to a real population.",
        "- **The guarantee is conditional** on exchangeability with the calibration month,",
        "  which demonstrably failed within two months on this data.",
        "- **No vulnerability information** exists in the dataset, so none was analysed.",
        "- **Costs are illustrative parameters** for comparing policies. No saving is",
        "  claimed.",
        "- **Age disparity is unresolved.** It is measured, reported, and not fixed.",
        "",
        f"_Generated {datetime.now(UTC).date().isoformat()}._",
        "",
    ]
    return "\n".join(lines)
